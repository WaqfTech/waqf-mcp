func tr(lang, key string) string {
	if values, ok := text[lang]; ok {
		if value, ok := values[key]; ok {
			return value
		}
	}
	return text["en"][key]
}

func topicLabel(lang, name string) string {
	switch name {
	case "Books & heritage":
		return tr(lang, "topic_books")
	case "Hadith":
		return tr(lang, "topic_hadith")
	case "Quran & tafsir":
		return tr(lang, "topic_quran")
	case "Scholarship search":
		return tr(lang, "topic_scholarship")
	case "Other":
		return tr(lang, "topic_other")
	default:
		return name
	}
}

func displayValue(lang, dimension, value string) string {
	if dimension != "provider" {
		return value
	}
	switch value {
	case "internal":
		return tr(lang, "provider_internal")
	case "gateway":
		return tr(lang, "provider_gateway")
	case "canonical":
		return tr(lang, "provider_canonical")
	default:
		return value
	}
}

func shortDay(day, lang string) string {
	parsed, err := time.Parse("2006-01-02", day)
	if err != nil {
		return day
	}
	loc := localeFor(lang)
	if lang == "ar" {
		return fmt.Sprintf("%d %s", parsed.Day(), loc.months[parsed.Month()-1])
	}
	return parsed.Format("Jan 2")
}
